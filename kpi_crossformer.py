"""## 4. 학습

### 학습 설정 요약
| 항목 | 값 |
|------|----|
| Optimizer | AdamW (lr=0.0005, weight_decay=0.05) |
| Loss | SmoothL1 (β=0.5) + λ×dwell_loss |
| LR Schedule | Warmup 5 epoch → ReduceLROnPlateau |
| Early Stopping | patience=20 |
| 타겟 공간 | log1p(구매수) + 체류시간 |

## 🔧 수정사항 — LR 스케줄러: Cosine Decay → ReduceLROnPlateau

### 기존 문제
기존 **Cosine Decay**는 val loss와 무관하게 epoch이 지날수록 LR을 무조건 감소시킴.

```
epoch 40:  val=0.4569,  lr=0.00046  ← 아직 개선 중
epoch 108: val=0.4528,  lr=0.00024  ← LR이 절반 이하, val은 0.004만 줄었는데 학습 종료
```

→ val이 아직 개선되고 있는데 LR이 먼저 바닥나서 Early Stopping이 트리거됨.

### 변경 내용 & 해결 목적
**ReduceLROnPlateau**: val loss가 `patience=10` epoch 동안 개선 없을 때만 LR을 절반으로 줄임.

| 항목 | Cosine Decay (변경 전) | ReduceLROnPlateau (변경 후) |
|------|-----------------------|---------------------------|
| LR 감소 조건 | 시간 경과 무조건 감소 | val loss 정체 시에만 감소 |
| 개선 중인 구간 | LR이 줄어 학습 방해 | LR 유지 → 계속 학습 가능 |
| 수렴 후 | LR이 이미 바닥 | 정체 감지 후 LR 절반으로 → 세밀 탐색 |

Warmup 5 epoch은 기존과 동일하게 유지하고, 그 이후부터 Plateau 스케줄러가 작동함.

## 🔧 수정사항 — Val EMA 스무딩 + patience 복원

### 기존 문제
Val 샘플이 15개뿐이라 샘플 1개의 예측 오차가 val loss 전체의 **6.7%** 를 차지함.  
그 결과 val loss가 매 epoch마다 크게 진동해 잘못된 판단을 유발함.

```
Epoch 28: val=0.4560  *   ← best 갱신
Epoch 35: val=0.4637      ← 0.008 급등 (샘플 1~2개가 틀린 것)
Epoch 38: val=0.4557  *   ← 다시 best
Epoch 40: val=0.4634      ← 또 0.008 급등
```

**Raw val로 판단했을 때 발생한 두 가지 부작용:**
1. **ReduceLROnPlateau** 가 진짜 정체가 아닌 노이즈 스파이크에 반응해 LR을 조기 감소
2. **Early Stopping** 이 실제 개선 추세인데도 스파이크를 보고 patience를 소진

### 변경 내용 & 해결 목적

**Val EMA (지수이동평균)** 로 val loss를 평활화한 뒤, 이 값으로 Early Stopping과 ReduceLROnPlateau를 판단.

```
ema_val = 0.7 × (이전 EMA) + 0.3 × (현재 val)
```

| 항목 | 변경 전 | 변경 후 | 해결하는 문제 |
|------|---------|---------|--------------|
| Early Stopping 기준 | raw val (노이즈 큼) | **EMA val** (평활화) | 노이즈 스파이크로 인한 조기 종료 방지 |
| Plateau 감지 기준 | raw val | **EMA val** | 가짜 정체 신호로 LR 조기 감소 방지 |
| patience | 20 | **30** | EMA도 천천히 반응하므로 여유 부여 |
| 학습 곡선 출력 | Train / Val | Train / Val(raw) / **Val(EMA)** | 평활화 효과 시각적으로 확인 가능 |
"""

def set_seed(seed=42):
    """재현성을 위해 모든 난수 시드를 고정한다."""
    random.seed(seed); np.random.seed(seed)
    torch.manual_seed(seed); torch.cuda.manual_seed_all(seed)


"""## 5. 평가 — KPI #2, #3, #5, #7, #8

### KPI 계산 방식
| KPI | 계산 방식 |
|-----|-----------|
| #2 전체 구매전환율 | 전체 토큰 구매수 합산 (proxy) |
| #3 구역별 체류시간 | dwell_head 예측값, 시간대 평균 |
| #5 고객군별 구매수 | C 차원 합산 |
| #7 체류 대비 전환 효율 | zone_buy / zone_dwell |
| #8 비효율 구역 지수 | minmax(체류) × (1 − minmax(전환)) |
"""

def compute_kpis(preds_p, trues_p, preds_d, trues_d, n_zones, n_hours, n_classes):
    """예측값에서 KPI #2, #3, #5, #7, #8을 계산한다."""
    Z, T, C = n_zones, n_hours, n_classes

    # log1p 역변환 → 원래 구매수 공간 복원
    p_buy = np.expm1(preds_p).clip(0)
    t_buy = np.expm1(trues_p)

    p4  = p_buy.reshape(-1, Z, T, C)   # [S*H, Z, T, C]
    t4  = t_buy.reshape(-1, Z, T, C)
    pd3 = preds_d.reshape(-1, Z, T)    # [S*H, Z, T]
    td3 = trues_d.reshape(-1, Z, T)

    def mape(p, t):
        mask = t > 0
        return float(np.mean(np.abs(p[mask] - t[mask]) / t[mask].clip(1e-6)) * 100) if mask.any() else float('nan')

    def minmax_norm(arr):
        return (arr - arr.min()) / (arr.max() - arr.min() + 1e-6)

    # KPI #2: 전체 구매수 총합 (proxy)
    total_p, total_t = p4.sum(axis=(1,2,3)), t4.sum(axis=(1,2,3))

    # KPI #3: 구역별 체류시간 (시간대 평균)
    zone_dwell_p, zone_dwell_t = pd3.mean(axis=2), td3.mean(axis=2)  # [S*H, Z]

    # KPI #5: 고객군별 구매수 (구역·시간대 합산)
    cls_p, cls_t = p4.sum(axis=(1,2)), t4.sum(axis=(1,2))             # [S*H, C]

    # KPI #7, #8 기반: 구역별 구매수
    zone_buy_p, zone_buy_t = p4.sum(axis=(2,3)), t4.sum(axis=(2,3))   # [S*H, Z]

    # KPI #7: 체류 대비 전환 효율 = 구매수 / 체류시간
    eff_p = zone_buy_p.mean(0) / (zone_dwell_p.mean(0) + 1e-6)
    eff_t = zone_buy_t.mean(0) / (zone_dwell_t.mean(0) + 1e-6)

    # KPI #8: 비효율 구역 지수 = norm(체류) × (1 - norm(전환))
    ineff_p = minmax_norm(zone_dwell_p.mean(0)) * (1 - minmax_norm(zone_buy_p.mean(0)))
    ineff_t = minmax_norm(zone_dwell_t.mean(0)) * (1 - minmax_norm(zone_buy_t.mean(0)))

    return {
        'kpi2_overall':     {'pred_mean': float(total_p.mean()), 'true_mean': float(total_t.mean()),
                             'mae': float(np.abs(total_p-total_t).mean()), 'mape': mape(total_p, total_t)},
        'kpi3_zone_dwell':  {'pred': zone_dwell_p.mean(0), 'true': zone_dwell_t.mean(0),
                             'mae': float(np.abs(zone_dwell_p-zone_dwell_t).mean()),
                             'mape': float((np.abs(zone_dwell_p-zone_dwell_t)/(zone_dwell_t+1e-6)).mean()*100),
                             'spearman': float(spearmanr(zone_dwell_p.mean(0), zone_dwell_t.mean(0)).statistic)},
        'kpi5_class':       {'pred': cls_p.mean(0), 'true': cls_t.mean(0),
                             'mape': float((np.abs(cls_p-cls_t)/(cls_t+1e-6)).mean()*100),
                             'spearman': float(spearmanr(cls_p.mean(0), cls_t.mean(0)).statistic)},
        'kpi7_efficiency':  {'pred': eff_p, 'true': eff_t,
                             'mape': float((np.abs(eff_p-eff_t)/(eff_t+1e-6)).mean()*100),
                             'spearman': float(spearmanr(eff_p, eff_t).statistic)},
        'kpi8_inefficiency':{'pred': ineff_p, 'true': ineff_t,
                             'spearman': float(spearmanr(ineff_p, ineff_t).statistic)},
    }

# 체크포인트 로드 & Test 데이터셋 생성
ckpt     = torch.load(ckpt_path, map_location=device, weights_only=False)
dc_ckpt  = ckpt['cfg_data']
mc_ckpt  = ckpt['cfg_model']

test_start = dc_ckpt['train_days'] + dc_ckpt['val_days'] + 1
test_ds    = KPIGridDataset(dc_ckpt['purchases_csv'], W, H,
                             day_range=(test_start, 9999), stats=ckpt['stats'])
test_loader = DataLoader(test_ds, batch_size=64)

# 모델 복원
model_eval = KPICrossformer(
    n_zones=ckpt['n_zones'], n_hours=ckpt['n_hours'], n_classes=ckpt['n_classes'],
    n_features=KPIGridDataset.N_FEATURES,
    d_model=mc_ckpt['d_model'], n_heads=mc_ckpt['n_heads'],
    n_layers=mc_ckpt['n_layers'], n_router=mc_ckpt['n_router'],
    dropout=mc_ckpt['dropout'], horizon=H, max_window=max(W, 64),
).to(device)
model_eval.load_state_dict(ckpt['model'])
model_eval.eval()   # Dropout 비활성화

# 추론
preds_p, trues_p, preds_d, trues_d = [], [], [], []
with torch.no_grad():
    for x, yp, yd, dow in test_loader:
        pp, pd = model_eval(x.to(device), dow.to(device))
        preds_p.append(pp.cpu().numpy()); trues_p.append(yp.numpy())
        preds_d.append(pd.cpu().numpy()); trues_d.append(yd.numpy())

preds_p = np.concatenate(preds_p); trues_p = np.concatenate(trues_p)
preds_d = np.concatenate(preds_d); trues_d = np.concatenate(trues_d)

# KPI 계산 & 출력
kpis = compute_kpis(preds_p, trues_p, preds_d, trues_d,
                    ckpt['n_zones'], ckpt['n_hours'], ckpt['n_classes'])


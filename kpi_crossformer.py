lam       = tc['lambda_dwell']

epochs, warmup = tc['epochs'], tc['warmup_epochs']

def lr_warmup(epoch):
    return (epoch + 1) / warmup if epoch < warmup else 1.0

warmup_scheduler  = torch.optim.lr_scheduler.LambdaLR(optimizer, lr_warmup)
plateau_scheduler = torch.optim.lr_scheduler.ReduceLROnPlateau(
    optimizer, mode='min', factor=0.5, patience=10, min_lr=1e-6
)

ckpt_path  = Path(tc['checkpoint_dir']) / 'best_kpi.pt'
best_ema   = float('inf')   # EMA 기준 best (Early Stopping 판단에 사용)
best_val   = float('inf')   # raw val best (체크포인트 저장 기준)
no_improve = 0
ema_val    = None           # Val loss EMA (지수이동평균)
EMA_ALPHA  = 0.3            # 최신 값 반영 비율 (낮을수록 더 많이 평활화)

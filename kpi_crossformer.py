"""## 2. Dataset — KPIGridDataset

### 전처리 파이프라인
```
batch_purchases CSV
        ↓
(일차, 구역ID, 시간대, 고객분류) 기준 groupby 집계
        ↓
3D grid [D, Z, T, C, F]   ← 고객군(C) 차원 추가 (원본 대비)
        ↓
정규화 (활성 셀 기준 mean/std, 수량형은 log1p 후 z-score)
        ↓
슬라이딩 윈도우 → (x [L, N, F], y_purchase [H, N], y_dwell [H, Z*T], dow [L])
```

### 입력 피처 4개 (F=4)
| idx | 피처 | 정규화 방식 |
|-----|------|-------------|
| 0 | 구매 이벤트 수 | log1p → z-score |
| 1 | 체류시간 평균 | z-score |
| 2 | 가격 평균 | z-score |
| 3 | 방문 고객 수 | log1p → z-score |

### 타겟 2종류
| 타겟 | shape | 설명 |
|------|-------|------|
| target_purchase | [H, Z\*T\*C] | log1p(구매수) — 336 토큰 전체 |
| target_dwell | [H, Z\*T] | 체류시간 — 고객군 차원 평균 |
"""

class KPIGridDataset(Dataset):
    """
    batch_purchases CSV를 3D grid로 변환하고 슬라이딩 윈도우 샘플을 반환한다.

    입력 형태: [window_size, Z*T*C, F]  (정규화된 피처)
    타겟 형태:
      purchase: [horizon, Z*T*C]  (log1p 구매수)
      dwell:    [horizon, Z*T]    (체류시간, 고객군 평균)
    """

    N_FEATURES = 4  # 구매수, 체류시간, 가격, 방문고객수

    def __init__(self, purchases_path, window_size=7, horizon=1,
                 day_range=None, stats=None):
        # ── 전체 CSV 로드 (카테고리 매핑은 항상 전체 기준) ──────
        df_all = pd.read_csv(purchases_path)
        df_all['hour'] = df_all['시간대'].str.replace('시', '').astype(int)

        # 카테고리를 전체 CSV 기준으로 정렬 → Train/Val/Test 간 인덱스 통일
        self.zones   = sorted(df_all['구역ID'].unique())
        self.hours   = sorted(df_all['hour'].unique())
        self.classes = sorted(df_all['고객분류'].unique())
        self.zone2idx = {z: i for i, z in enumerate(self.zones)}
        self.hour2idx = {h: i for i, h in enumerate(self.hours)}
        self.cls2idx  = {c: i for i, c in enumerate(self.classes)}
        self.n_zones   = len(self.zones)
        self.n_hours   = len(self.hours)
        self.n_classes = len(self.classes)
        self.n_tokens  = self.n_zones * self.n_hours * self.n_classes  # 336

        # ── day_range 필터 적용 ─────────────────────────────────
        df = (df_all if day_range is None
              else df_all[df_all['일차'].between(*day_range)])
        days_present = sorted(df['일차'].unique())
        n_days = len(days_present)
        self.day2seq = {d: i for i, d in enumerate(days_present)}
        self.seq2day = {i: d for d, i in self.day2seq.items()}

        # ── 3D grid 빌드 & 정규화 ──────────────────────────────
        self.grid_raw = self._build_grid(df, n_days)
        self.stats    = stats if stats is not None else self._fit_stats(self.grid_raw)
        self.grid     = self._normalize(self.grid_raw, self.stats)

        # ── 타겟 생성 ───────────────────────────────────────────
        # 타겟 1: 구매수 — long-tail 완화를 위해 log1p 변환
        self.target_purchase_raw = self.grid_raw[..., 0]                       # [D, Z, T, C]
        self.target_purchase     = np.log1p(self.target_purchase_raw).astype(np.float32)

        # 타겟 2: 체류시간 — 고객군(C) 차원 평균 → 구역×시간대 단위
        self.target_dwell_raw = self.grid_raw[..., 1].mean(axis=-1)            # [D, Z, T]
        self.target_dwell     = self.target_dwell_raw.astype(np.float32)

        # ── 슬라이딩 윈도우 인덱스 ─────────────────────────────
        self.window_size = window_size
        self.horizon     = horizon
        max_start        = n_days - window_size - horizon + 1
        self.indices     = list(range(max(0, max_start)))

    def _build_grid(self, df, n_days):
        """CSV를 (일차, 구역, 시간대, 고객분류) 기준으로 집계해 5D 배열로 변환한다."""
        Z, T, C, F = self.n_zones, self.n_hours, self.n_classes, self.N_FEATURES
        grid = np.zeros((n_days, Z, T, C, F), dtype=np.float32)

        for (day, zone, hour, cls), grp in df.groupby(['일차', '구역ID', 'hour', '고객분류']):
            if day not in self.day2seq:
                continue
            d, zi, ti = self.day2seq[day], self.zone2idx[zone], self.hour2idx[hour]
            ci = self.cls2idx.get(cls)
            if ci is None:
                continue

            grid[d, zi, ti, ci, 0] = len(grp)                  # 구매 수
            grid[d, zi, ti, ci, 1] = grp['체류시간'].mean()     # 평균 체류시간
            grid[d, zi, ti, ci, 2] = grp['가격'].mean()         # 평균 가격
            grid[d, zi, ti, ci, 3] = grp['에이전트ID'].nunique()    # 방문 고객 수

        return grid

    @staticmethod
    def _fit_stats(grid):
        """Train grid에서 정규화 통계(mean, std)를 계산한다. 활성 셀만 사용."""
        F    = grid.shape[-1]
        flat = grid.reshape(-1, F)
        nz   = flat[flat[:, 0] > 0]   # 구매 있는 셀만 (0 셀이 통계를 왜곡하지 않도록)
        log_idx = {0, 3}              # 카운트형 피처: log1p 후 정규화
        means, stds = np.zeros(F, np.float32), np.ones(F, np.float32)

        for i in range(F):
            col = nz[:, i] if len(nz) else flat[:, i]
            if i in log_idx:
                col = np.log1p(col)
            means[i] = col.mean() if len(col) else 0.0
            stds[i]  = col.std()  + 1e-6

        return {'means': means, 'stds': stds, 'log_idx': list(log_idx)}

    @staticmethod
    def _normalize(grid, stats):
        """fit_stats 통계로 z-score 정규화한다. log_idx 피처는 log1p 먼저 적용."""
        out, log_idx = grid.copy(), set(stats['log_idx'])
        for i in range(grid.shape[-1]):
            if i in log_idx:
                out[..., i] = np.log1p(out[..., i])
            out[..., i] = (out[..., i] - stats['means'][i]) / stats['stds'][i]
        return out.astype(np.float32)

    def __len__(self):
        return len(self.indices)

    def __getitem__(self, idx):
        """슬라이딩 윈도우 샘플을 반환한다. (x, y_purchase, y_dwell, dow)"""
        s   = self.indices[idx]
        x   = self.grid[s: s + self.window_size]                              # [L, Z, T, C, F]
        yp  = self.target_purchase[s+self.window_size: s+self.window_size+self.horizon]  # [H, Z, T, C]
        yd  = self.target_dwell[s+self.window_size: s+self.window_size+self.horizon]     # [H, Z, T]
        days = [self.seq2day[s + i] for i in range(self.window_size)]
        dow  = np.array([(d - 1) % 7 for d in days], dtype=np.int64)         # [L]

        L, Z, T, C, F = x.shape
        return (torch.from_numpy(x.reshape(L, Z*T*C, F)),
                torch.from_numpy(yp.reshape(self.horizon, Z*T*C)),
                torch.from_numpy(yd.reshape(self.horizon, Z*T)),
                torch.from_numpy(dow))

# 데이터셋 생성 및 shape 확인

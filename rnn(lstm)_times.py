"""# 6. Test Evaluation

6번 코드는 학습 과정에서 validation loss가 가장 낮았던 최적 모델을 불러와 test set에서 최종 성능을 평가하는 부분이다. 저장된 checkpoint에서 모델 가중치를 불러오고, test_loader에 있는 데이터를 이용해 예측값과 실제값을 수집한다. 이후 MAE, RMSE, MAPE, sMAPE 지표를 계산하여 모델의 예측 성능을 정량적으로 평가한다. MAE와 RMSE는 예측값과 실제값의 평균적인 오차 크기를 보여주며, MAPE와 sMAPE는 비율 기반 오차를 확인하는 데 사용된다. 이를 통해 모델이 학습 데이터뿐만 아니라 새로운 test 데이터에서도 얼마나 안정적으로 예측하는지 확인할 수 있다.
"""

# =========================================================
# 6. Test Evaluation
# =========================================================

from sklearn.metrics import mean_absolute_error, mean_squared_error

ckpt = torch.load(
    "best_zone_hour_lstm.pt",
    map_location=device,
    weights_only=False
)

model.load_state_dict(ckpt["model_state"])
model.eval()

preds = []
trues = []

with torch.no_grad():
    for x, y in test_loader:
        x = x.to(device)

        pred = model(x).cpu().numpy()

        preds.append(pred)
        trues.append(y.numpy())

preds = np.concatenate(preds, axis=0)
trues = np.concatenate(trues, axis=0)

# ===== metrics =====
mae = mean_absolute_error(trues.flatten(), preds.flatten())
rmse = np.sqrt(mean_squared_error(trues.flatten(), preds.flatten()))

mask = trues > 1e-6
mape = np.mean(np.abs((preds[mask] - trues[mask]) / trues[mask])) * 100

smape = np.mean(
    2 * np.abs(preds - trues) /
    (np.abs(preds) + np.abs(trues) + 1e-6)
) * 100

print("===== Test Result: Zone-Hour LSTM =====")
print(f"MAE   : {mae:.6f}")
print(f"RMSE  : {rmse:.6f}")
print(f"MAPE  : {mape:.2f}%")
print(f"sMAPE : {smape:.2f}%")

"""# 7. Persistence Baseline 비교

7번 코드는 LSTM 모델의 성능을 단순 기준 모델인 Persistence Baseline과 비교하는 과정이다. Persistence Baseline은 전날의 구역·시간대별 구매비중이 다음 날에도 동일하게 유지된다고 가정하는 단순 예측 방식이다. 이 baseline은 시계열 예측 문제에서 최소한으로 넘어서야 하는 기준 성능으로 활용된다. LSTM 모델의 MAE와 RMSE를 baseline의 MAE, RMSE와 비교하여 개선율을 계산함으로써, 모델이 단순히 전날 값을 복사하는 수준을 넘어 실제 시계열 패턴을 학습했는지 평가할 수 있다.
"""

# =========================================================
# 7. Persistence Baseline
# =========================================================

baseline_preds = []
baseline_trues = []

for i in range(len(test_ds)):
    x, y = test_ds[i]

    # 전날 값 그대로 예측
    last_day_share = x[-1, :, 8].numpy()

    baseline_preds.append(last_day_share)
    baseline_trues.append(y.numpy())

baseline_preds = np.array(baseline_preds)
baseline_trues = np.array(baseline_trues)

# ===== baseline metrics =====
base_mae = mean_absolute_error(
    baseline_trues.flatten(), baseline_preds.flatten()
)
base_rmse = np.sqrt(mean_squared_error(
    baseline_trues.flatten(), baseline_preds.flatten()
))

mask = baseline_trues > 1e-6
base_mape = np.mean(
    np.abs((baseline_preds[mask] - baseline_trues[mask]) / baseline_trues[mask])
) * 100

base_smape = np.mean(
    2 * np.abs(baseline_preds - baseline_trues) /
    (np.abs(baseline_preds) + np.abs(baseline_trues) + 1e-6)
) * 100

print("===== Persistence Baseline =====")
print(f"MAE   : {base_mae:.6f}")
print(f"RMSE  : {base_rmse:.6f}")
print(f"MAPE  : {base_mape:.2f}%")
print(f"sMAPE : {base_smape:.2f}%")

# ===== improvement =====
print("\n===== Improvement =====")

if base_mae > 0:
    print(f"MAE improvement  : {(base_mae - mae) / base_mae * 100:.2f}%")
else:
    print("MAE improvement  : 계산 불가")

if base_rmse > 0:
    print(f"RMSE improvement : {(base_rmse - rmse) / base_rmse * 100:.2f}%")
else:
    print("RMSE improvement : 계산 불가")

